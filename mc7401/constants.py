"""
constants.py — константы и коды терминала «Электроника МС 7401».

Все коды приведены в восьмеричной записи (`0o…`), как это принято
в исходных текстах `graf.pas` (константы `ВК`, `АР2`, `S0`, `S1`, `LF`,
`ЕND`) и в статье:

    А. О. Лацис, В. С. Штаркман. Системы команд растрового графического
    дисплея «Электроника МС7401» // Микропроцессорные средства и системы.
    — 1989. — № 5. — С. 39–44.
"""

from __future__ import annotations

# ─────────────────────────────────────────────────────────────────────────────
# Геометрия экрана и видеопамяти
# ─────────────────────────────────────────────────────────────────────────────

#: Разрешение экрана, точек (статья МПСС 5/1989, с. 40: «Размеры экрана —
#: 560 × 400 точек, формат видеопамяти — 7 точек на 1 байт»).
SCREEN_WIDTH = 560
SCREEN_HEIGHT = 400

#: Объём видеопамяти ≈ 32 Кбайт = SCREEN_WIDTH*SCREEN_HEIGHT/7.
VIDEOMEM_BYTES = SCREEN_WIDTH * SCREEN_HEIGHT // 7

# ─────────────────────────────────────────────────────────────────────────────
# Базовые управляющие коды
# ─────────────────────────────────────────────────────────────────────────────

#: `П1` — разделитель параметров команды (пробел).
P1 = 0x20  # ' '

#: `ВК` — конец команды / команды-разделитель.  0o125 = 85 = 'U'.
VK = 0o125

#: `АР2` — префикс специальной функции (ESC).  0o124 = 84 = 'T'.
AR2 = 0o124

#: `S0` — переключение на русский шрифт.  0o160 = 112 = 'p'.
S0 = 0o160

#: `S1` — переключение на латинский шрифт.  0o161 = 113 = 'q'.
S1 = 0o161

#: `LF` — команда смещения окна.  0o175 = 125 = '}'.
LF = 0o175

#: `ЕND` — маркер конца текста / конца ввода.  0o377 = 255.
#: Гид-символ ОС Диспак; для линии ДКС ETX — просто знак, строку
#: не завершает (окончание строки — ПР, см. `[line] eol`).
ETX = 0o003

END = 0o377

#: `ПЛС` — рисующее перо (OR).
CMD_PLUS = ord('+')  # 0x2B

#: `НЕР` — инвертирующее перо (XOR).
#:
#: В исходнике `graf.pas` записано как `НЕР=’≠’`. Символ «≠» отсутствует
#: в семибитном алфавите терминала, поэтому в потоке команд он передаётся
#: служебным кодом из блока 0o241…0o277 (см. ниже). Здесь выбран код
#: 0o256 = 174; при необходимости он переопределяется через переменную
#: окружения `MC7401_XOR_CODE` или аргументом `--xor-code`.
CMD_NOT = 0o256

# ─────────────────────────────────────────────────────────────────────────────
# Служебные коды графического процессора
# ─────────────────────────────────────────────────────────────────────────────

#: Начало подпрограммы-знака (команда СПЕЦ в `graf.pas`).
SC_DEFCHAR = 0o110  # 72  = 'H'

#: Начало строки-параметра (знакового задания).
SC_ROW = 0o240  # 160

#: Конец текста / конец знака.
SC_ENDTEXT = 0o215  # 141

#: Начало кадра вывода (равен `LF`).
SC_FRAME = 0o257  # 175 = '}' = LF

#: Начало строки текста: ESC + 0o306 + 0o336 + 0o215.
SC_TXT_LINE = bytes((0o33, 0o306, 0o336, 0o215))

#: Возврат к русскому шрифту после строки текста.
SC_TXT_RU = bytes((0o273, 0o240))

#: Символы-точки знакоместа 3×3, используемые в СПЕЦ (`WN` в `graf.pas`).
#: Загружаются в терминал командой `≡110 ≡240 …`.
SC_DOTS = tuple(0o260 + i for i in range(1, 11))  # 177…185

#: Блок кодов «внутренних функций» терминала.
SC_INTERNAL = range(0o240, 0o300)

# ─────────────────────────────────────────────────────────────────────────────
# Коды команд
# ─────────────────────────────────────────────────────────────────────────────

#: Префикс графической команды: `АР2 'У  '` — включение графического входа.
ESC_GRAPH = b'\x54'  # 'T' — собирается вместе с символом функции

#: `АР2 'F‾' ВК` — конец кадра / вывод на экран.
ESC_FRAME = b'\x46'  # 'F'

#: `К` — сброс терминала (в `НАЧГРАФ`).
CMD_RESET = ord('K')

#: `S` — очистка экрана (в `НАЧГРАФ`).
CMD_CLEAR = ord('S')

# ─────────────────────────────────────────────────────────────────────────────
# Перья и режимы
# ─────────────────────────────────────────────────────────────────────────────

PEN_OR = 'OR'          # рисующее
PEN_XOR = 'XOR'        # инвертирующее
PEN_ERASE = 'ERASE'    # стирающее

#: Значения параметра команды `0 C` (установка пера).
PEN_BY_CODE = {
    '0': PEN_OR,
    '1': PEN_XOR,
    '2': PEN_ERASE,
}

# ─────────────────────────────────────────────────────────────────────────────
# Типы линий 0…7
# ─────────────────────────────────────────────────────────────────────────────

#: Тип 6 в терминале отключён («6 НЕЛЬЗЯ» в `graf.pas`).
LINE_TYPE_DISABLED = 6

#: Восьмиразрядные шаблоны типов линий (старший бит идёт первым).
#: Значения восстановлены по описанию из AGENTS.md/README и по рисунку
#: образцов типов линий в `graf.pas` (процедура `ЛИНИИ`).
LINE_PATTERNS = {
    0: (1, 1, 1, 1, 1, 1, 1, 1),      # сплошная
    1: (1, 1, 1, 1, 1, 1, 1, 1),      # сплошная тонкая
    2: (1, 1, 1, 0, 1, 1, 1, 0),      # штриховая
    3: (1, 1, 0, 0, 1, 1, 0, 0),      # пунктирная
    4: (1, 1, 1, 0, 0, 0, 1, 0),      # штрих-пунктирная
    5: (1, 0, 0, 0, 1, 0, 0, 0),      # точечная
    6: (0, 0, 0, 0, 0, 0, 0, 0),      # отключена
    7: (1, 1, 0, 0, 0, 0, 0, 0),      # редкая штриховая
}

# ─────────────────────────────────────────────────────────────────────────────
# Текст
# ─────────────────────────────────────────────────────────────────────────────

#: Знакомест терминала: 7 точек по горизонтали, 8 по вертикали.
GLYPH_W = 7
GLYPH_H = 8

#: Число знаков пользовательской таблицы (команда `≡110`).
USER_CHARS = 64

#: Число направлений строки текста (0…7).
TEXT_DIRECTIONS = 8

#: Число размеров шрифта (параметр `S` команды `9`).
TEXT_SIZES = 4