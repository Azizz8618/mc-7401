"""
native.py — родной алфавит команд терминала «Электроника МС 7401».

Таблица восстановлена из программы `graf1.pas` (процедуры `ВЫД`/`РИС`),
которая перед выводом в линию перекодирует поток команд:

    a[i] := chr(sel(map.c[ord(a[i]) div 4],
                    27 - ord(a[i]) mod 4 * 9, 8));

`map.c` — 32 ячейки по 36 бит (12 восьмеричных разрядов), каждая
хранит четыре 9-разрядных кода; из них терминал берёт 8 бит.

Таким образом каждому семибитному коду `b` соответствует родной код
терминала:

    native(b) = (map.c[b div 4] >> (9 * (b mod 4))) & 0o177

Обратное преобразование (`denative`) используется при разборе потока,
пришедшего от реального терминала.
"""

from __future__ import annotations

#: 32 ячейки по 12 восьмеричных разрядов (из `graf1.pas`).
MAP_TABLE = (
    0o060261262063, 0o264065066267, 0o270071053055, 0o257254056240,
    0o140300050251, 0o300275273333, 0o335252077047, 0o243074276072,
    0o101342102347, 0o344305366372, 0o151152113154, 0o115110317360,
    0o120303324131, 0o146330143176, 0o173175371170, 0o374140161104,
    0o306107311312, 0o314116321322, 0o123125126327, 0o132336074276,
    0o077246077077, 0o033215245044, 0o374055137041, 0o042137077140,
    0o000012377171, 0o141124153166, 0o160164126003, 0o131043066156,
    0o216017237113, 0o147050115014, 0o210030000150, 0o215134231232,
)


def native(code: int) -> int:
    """Перевести семибитный код команды в родной код терминала."""
    b = code & 0o177
    return (MAP_TABLE[b >> 2] >> (9 * (b & 3))) & 0o177


def denative(code: int) -> int:
    """Обратное преобразование: родной код терминала → семибитный код."""
    return _INVERSE[code & 0o177]


#: Обратная таблица `родной код → семибитный код`.
_INVERSE: dict[int, int] = {}
for _b in range(0o200):
    _n = native(_b)
    _INVERSE.setdefault(_n, _b)

#: Родные коды основных команд (получены подстановкой кодов `graf.pas`).
NATIVE = {
    'J': native(ord('J')),   # начало команд `J0` / `J1`
    '0': native(ord('0')),   # установка пера
    '1': native(ord('1')),   # установка типа линии
    '2': native(ord('2')),   # конец кадра
    '3': native(ord('3')),   # конец обновления
    '4': native(ord('4')),   # перемещение (абсолютное)
    '5': native(ord('5')),   # перемещение (относительное)
    '7': native(ord('7')),   # отрезок до точки (абсолютной)
    '8': native(ord('8')),   # отрезок относительно точки
    '9': native(ord('9')),   # текст
    ']': native(ord(']')),   # прямоугольник
    '>': native(ord('>')),   # окружность
    '+': native(ord('+')),   # рисующее перо
    ';': native(ord(';')),   # начало строки текста
    ':': native(ord(':')),   # параметр текста
    '=': native(ord('=')),
    '*': native(ord('*')),   # стирающее перо
    'K': native(ord('K')),   # сброс
    'S': native(ord('S')),   # очистка экрана
    ' ': native(ord(' ')),   # разделитель параметров
    '/': native(ord('/')),   # начало блока ВУК
    '}': 0o031,              # смещение окна (LF из `graf.pas`)
}

#: Родные коды служебных последовательностей `graf.pas`.
NATIVE_SPECIAL = {
    '≡033': native(0o33),
    '≡060…≡071': native(ord('0')),
    '≡110': native(0o110),
    '≡135': native(0o135),
    '≡172': native(0o172),
    '≡215': native(0o215),
    '≡240': native(0o240),
    '≡257': native(0o257),
    '≡261…≡271': native(0o261),
    '≡273': native(0o273),
    '≡306': native(0o306),
    '≡336': native(0o336),
}


def encode(stream: bytes) -> bytes:
    """Перекодировать поток в родной алфавит терминала."""
    return bytes(native(b) for b in stream)


def decode(stream: bytes) -> bytes:
    """Перевести поток из родного алфавита в семибитные коды."""
    return bytes(denative(b) for b in stream)