# Латинские знаки в кодах 0o40…0o177 (7 бит).
GLYPHS_LAT: dict[int, tuple[int, ...]] = {}
for _i, _c in enumerate(
    " !\"#$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_`"
    "abcdefghijklmnopqrstuvwxyz{|}~"
):
    GLYPHS_LAT[0o40 + _i] = _FONT_5X7[_c]

# Русские знаки.  Терминал работает семибитными кодами (ст. 40 статьи:
# «7 бит используется в каждом байте»), поэтому на русской странице
# (`S0`) семибитный код `c` соответствует коду КОИ-8 `c | 0x80`:
# `п` = 0x70, `и` = 0x69, `т` = 0x74.
#
# Таблица строится по стандартному кодеку `koi8-r`, а не вручную:
# прежняя ручная таблица была записана кодами в восьмеричной записи
# вместо шестнадцатеричной (`0o160` = 112 — это не КОИ-8), из-за чего
# все кириллические знаки смещались и выводились случайными рисунками.
GLYPHS_RU: dict[int, tuple[int, ...]] = {}
for _code7 in range(0x00, 0x80):
    try:
        _ch = bytes((_code7 | 0x80,)).decode('koi8-r')
    except UnicodeDecodeError:                 # pragma: no cover
        continue
    GLYPHS_RU[_code7] = _FONT_5X7.get(_ch, _FONT_5X7['?'])

#: Латинская таблица с учётом псевдографики (коды 0o200…0o277).
for _code, _pat in _BOX.items():
    GLYPHS_LAT[_code & 0xFF] = _pat

