class UserCharTable:
    """64 переопределяемых знака 7×7 (команда `≡110`).

    Знак задаётся семью байтами-строками, по одному на ряд знакоместа,
    бит 6 — самый левый (как в `graf.pas`, где биты идут от 6-го к 0-му).
    """

    def __init__(self) -> None:
        self.chars: list[tuple[int, ...] | None] = [None] * USER_CHARS

    def define(self, index: int, rows: Sequence[int]) -> None:
        if not 0 <= index < USER_CHARS:
            raise IndexError(f'знак {index} вне таблицы 0…{USER_CHARS - 1}')
        if len(rows) != 7:
            raise ValueError('знак должен содержать 7 строк')
        matrix = []
        for r in rows:
            bits = [(r >> (6 - b)) & 1 for b in range(GLYPH_W)]
            matrix.append(tuple(bits))
        self.chars[index] = tuple(matrix)

    def clear(self) -> None:
        self.chars = [None] * USER_CHARS

    def get(self, index: int) -> tuple[tuple[int, ...], ...] | None:
        if not 0 <= index < USER_CHARS:
            return None
        mat = self.chars[index]
        if mat is None:
            return None
        return mat + ((0,) * (GLYPH_H - len(mat)),)


#: Глобальная таблица пользовательских знаков терминала.
USER_TABLE = UserCharTable()


