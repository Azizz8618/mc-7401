# Наборов **ввода** у МС 7401 два (клавиша F8 «НАБОР», `session.toggle_charset`):
#
# * `'n2'`    — **Н2 (КОИ-7)**: семибитная строка линии ДКС.  Кириллица
#              лежит в строке `0x60…0x7E` порядком КОИ-7, регистр
#              сворачивает машина, а на месте строчных латинских букв
#              в этой строке стоит кириллица — поэтому набранная строчная
#              латинская уходит **заглавной** (`KOI7_LAT_UPPER`).  Набор
#              по умолчанию: с ним работает живая линия ДКС.
# * `'koi8r'` — **КОИ-8Р**: восьмибитный, кириллица в 0xC0…0xFF,
#              латиница в обоих регистрах; оператор переходит на него сам
#              (F8), когда нужен регистр латиницы или восьмибитный КОИ-8.
#
# Набор **выдачи** (`display_char`, страницы `S0`/`S1`) остаётся КОИ-8Р:
# линия ДКС в режиме `raw` (`set ttyN dks,raw`) присылает семибитные коды
# КОИ-7, и их разбирает `display_dks`.  Переключение набора ввода на
# выдачу ЭВМ не влияет — это разные вещи, и оператор вправе переключать
# первое, не трогая второе.

