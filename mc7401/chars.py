# Каждый знак — 7 строк по 5 бит (бит 4 — самый левый).  Таблица построена
# по стандартному 5×7 ASCII-набору, используемому в отечественной
# знакогенерации 80-х годов; знаки КОИ-8 получают те же начертания, что и
# латинские (в реальном терминале начертания задаются ПЗУ).
def _row_bits(row: str) -> int:
    """Строка рисунка (`.`/`#`) → 5 бит; крайний слева — бит 4."""
    v = 0
    for i, ch in enumerate(row[:5]):
        if ch == '#':
            v |= 1 << (4 - i)
    return v


