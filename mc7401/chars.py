#: Направления строки текста: 8 векторов (см. `DIRECTION_VECTORS`).
#: Углы отсчитываются против часовой стрелки от направления «слева направо».
DIRECTION_VECTORS = (
    (1, 0), (0.70711, 0.70711), (0, 1), (-0.70711, 0.70711),
    (-1, 0), (-0.70711, -0.70711), (0, -1), (0.70711, -0.70711),
)


def glyph_matrix(code: int, russian: bool) -> tuple[tuple[int, ...], ...]:
    """Матрица знака 7×8 по его семибитному коду.

    Сначала проверяется пользовательская таблица (команда `≡110`), затем —
    встроенная таблица текущего шрифта.
    """
    code &= 0x7F
    if 0 <= code < USER_CHARS:
        custom = USER_TABLE.get(code)
        if custom is not None:
            return custom
    table = _RU_MATRIX if russian else _LAT_MATRIX
    return table.get(code, _LAT_MATRIX[0o40])


def dot_pattern(value: int) -> tuple[tuple[int, int, int], ...]:
    """Знак «N точек в знакоместе 3×3» — символы СПЕЦ (`WN` в `graf.pas`).

    `value` = 0…9 — число точек; знакомест заполняется построчно снизу вверх.
    """
    cells = [[0, 0, 0], [0, 0, 0], [0, 0, 0]]
    left = max(0, min(9, value))
    for cy in (2, 1, 0):
        for cx in range(3):
            if left == 0:
                break
            cells[cy][cx] = 1
            left -= 1
        if left == 0:
            break
    return tuple(tuple(r) for r in cells)


def dots_matrix(value: int) -> tuple[tuple[int, ...], ...]:
    """Матрица 7×7 знака из семи трёхразрядных октетов (`WS` в `graf.pas`).

    Семиразрядное значение разбивается на три октета по три бита
    (биты 6…4, 3…1, 0), каждый из которых кодирует знак «N точек в
    знакоместе 3×3» — так СПЕЦ передаёт произвольный рисунок 7×7.
    """
    out = []
    for r in range(7):
        octet = (value >> (6 - 3 * r)) & 0o7
        cells = dot_pattern(octet)
        out.append(tuple(cells[0] + cells[1] + cells[2]))
    return tuple(out)


def scale_matrix(matrix: Sequence[Sequence[int]], size: int) -> list[list[int]]:
    """Увеличить знак в `size` раз (size ≤ 1 — без изменений)."""
    rows = [list(r) for r in matrix]
    if size <= 1:
        return rows
    return [[v for v in row for _ in range(size)] for row in rows for _ in range(size)]


# ── текстовая строка: преобразование знакоместа в экранные смещения ─────────

def _transform(direction: int, size: int):
    """Вернуть отображение (u, v) → (dx, dy) для знака в строке текста.

    `u` — столбец знакоместа (0…6), `v` — строка сверху вниз (0…7),
    `size` — множитель (габарит знака).
    """
    ca, sa = DIRECTION_VECTORS[direction % 8]
    # Поворот знака внутри знакоместа: (u, v) -> ось «вперёд по строке» и
    # «вверх от строки».  Базовый случай d=0: вперёд = u, вверх = -v.
    def xform(u: int, v: int) -> tuple[float, float]:
        # Точка в «локальной» системе: X вперёд, Y вверх от базовой линии.
        X = u - size * GLYPH_W / 2.0
        Y = size * (GLYPH_H - 1 - v)
        return X * ca - Y * sa, X * sa + Y * ca
    return xform


def text_advance(direction: int, size: int) -> tuple[float, float]:
    """Шаг между знаками строки текста (в точках экрана)."""
    ca, sa = DIRECTION_VECTORS[direction % 8]
    step = GLYPH_W * size + 1
    return step * ca, step * sa


def text_offsets(matrix: Sequence[Sequence[int]], direction: int, size: int):
    """Список смещений (dx, dy) для всех зажжённых точек знака.

    Начало строки (базовая линия первого знака) считается точкой (0, 0);
    знак «висит» над ней по направлению 0 и так далее для остальных.
    """
    xform = _transform(direction, size)
    pts = []
    for v, row in enumerate(matrix):
        for u, bit in enumerate(row):
            if not bit:
                continue
            dx, dy = xform(u * size, v * size)
            pts.append((int(round(dx)), int(round(dy))))
    return pts


def render_text(text: bytes, russian: bool, direction: int, size: int,
                start: int = 0) -> list[tuple[int, int]]:
    """Собрать список абсолютных смещений для строки `text`.

    `start` — с какого знака начинать (знаки с S0/S1/управляющими кодами
    в строке не выводятся, но занимают позицию только при явном задании).
    """
    ux, uy = text_advance(direction, size)
    pts: list[tuple[int, int]] = []
    for n, code in enumerate(text):
        mat = glyph_matrix(code, russian)
        for dx, dy in text_offsets(mat, direction, size):
            pts.append((int(round(ux * n + dx)), int(round(uy * n + dy))))
    return pts

