# ── Наборы знаков ──────────────────────────────────────────────────────────
#
# Модель наборов взята из эмулятора терминала «Электроника-15ИЭ»
# (`ie15/ie15emu/charset.py`, `session.py`), где она описана так:
#
#   Н0 — знаки ASCII (ISO 646 IRV: 0x24 «¤», 0x5E «¬», 0x7E «¯»),
#        команды — только управляющие;
#   Н1 — русские знаки верхнего и нижнего регистра (КОИ-7 Н1:
#        0x40…0x5E — заглавные, 0x5F — «Ъ», 0x60…0x7E — строчные);
#   Н2 — набор команд №2 (VT-52) — ПО УМОЛЧАНИЮ, с ним терминал работает
#        с БЭСМ-6; знаки — международная строка, русские приходят
#        кодами ЭВМ (как их отдаёт SIMH/ДКС).
#
# Для МС 7401 это согласуется со статьёй «Дисплейные микроконтроллеры
# семейства МИДИКОН» (МПСС, 1989, № 5, стр. 40): «система команд
# терминала VT-52 фирмы ДЕС с кодировкой 7 бит». Коды `S0`/`S1` внутри
# текста — это переключение набора: `S0` → Н1 (русский), `S1` → Н2
# (международный).

#: Наборы знаков МС 7401 — их два, а не как у 15ИЭ:
#:
#: * `'n2'`    — **Н2 (КОИ-7)**: набор команд №2 VT-52, как в терминале
#:              15ИЭ.  Международная строка, кириллица приходит кодами
#:              ЭВМ 0x00…0x1E, 0x1F — «№». **Набор по умолчанию.**
#: * `'koi8r'` — **КОИ-8Р**: кириллица на местах латиницы в верхней
#:              строке и в 0x60…0x7F, псевдографика в 0x80…0x9F.
#:
#: Семибитные коды у них совпадают для кириллицы (`п` = 0x70 в обоих,
#: `П` = 0x10 в обоих), поэтому поток читается одинаково; различаются
#: они в верхней половине строки и в знаках псевдографики.
SETS = ('n2', 'koi8r')

#: Набор по умолчанию — Н2 (КОИ-7), как в терминале 15ИЭ.
DEFAULT_SET = 'n2'

#: Подписи наборов для интерфейса.
SET_LABELS = {'n2': 'Н2 (КОИ-7)', 'koi8r': 'КОИ-8Р'}

#: Замены ISO 646 IRV в наборе Н0 (в Н2 они не действуют).
N0_SPECIAL = {0x24: '¤', 0x5E: '¬', 0x7E: '¯'}

#: Русский алфавит набора Н1 — порядок ПЗУ знакогенератора КР556РТ5.
RUS7 = 'ЮАБЦДЕФГХИЙКЛМНОПЯРСТУЖВЬЫЗШЭЩЧ'

#: Смещение строчных в Н1 (0x60…0x7E).
_LOWER_OFFSET = 0x60


def display_char(code: int, name: str = DEFAULT_SET) -> str:
    """Знак семибитного кода в данном наборе.

    Н2 (КОИ-7) — по правилам терминала 15ИЭ: международная строка,
    кириллица кодами ЭВМ 0x00…0x1E, 0x1F — «№».  КОИ-8Р — стандартная
    русская раскладка: 0x40…0x5F латиница, 0x60…0x7F кириллица.
    """
    code &= 0x7F
    if name == 'koi8r':
        return _koi8r_label(code)
    if True:
        if code == 0x1F:
            return '№'
        if code >= 0x20:
            if code == 0x7F:
                return '█'
            return chr(code)
    if name in ('n0', 'n2') and code >= 0x20:
        if code == 0x7F:
            return '█'
        return N0_SPECIAL.get(code, chr(code))
    if name == 'n0':
        return ''                              # ASCII: коды <0x20 — УП
    if name == 'n1' and 0x40 <= code <= 0x5F:
        code -= 0x40                           # латинская строка → русский верх
    return koi7_label(code)


def koi7_label(code: int) -> str:
    """Семибитный код Н1 → знак (пустая строка для управляющих)."""
    code &= 0x7F
    if code < len(RUS7):
        return RUS7[code]
    if code == 0x1F:
        return 'Ъ'
    if _LOWER_OFFSET <= code < 0x7F:
        return RUS7[code - _LOWER_OFFSET].lower()
    return ''


def _koi8r_label(code: int) -> str:
    """Семибитный код → знак в наборе КОИ-8Р."""
    code &= 0x7F
    if code == 0x7F:
        return '█'
    try:
        return bytes((code | 0x80,)).decode('koi8-r')
    except UnicodeDecodeError:
        return chr(code)


def apply_set(code: int, name: str = DEFAULT_SET) -> int:
    """Код терминала → код отображения в выбранном наборе."""
    return code & 0x7F


def set_for_code(code: int) -> Optional[str]:
    """Набор, включаемый управляющим кодом `S0` / `S1`.

    `S0` — русский набор КОИ-8Р, `S1` — международный Н2 (КОИ-7),
    то есть возврат к набору по умолчанию.  Так их использует
    `ТЕКФАЙ` в `graf.pas`: перед русскими знаками посылается `S0`.
    """
    from .constants import S0, S1
    if code == S0:
        return 'koi8r'
    if code == S1:
        return 'n2'
    return None

#: Знаки, которыми SIMH/ДКС пользуется вместо типографских.
INPUT_FALLBACK = {'\u2013': 0x2D, '\u2014': 0x2D, '\u2019': 0x27}


def encode_input(text: str, *, set_name: str = DEFAULT_SET,
                 line_end: bool = False) -> bytes:
    """Знаки с клавиатуры → байты линии ДКС, как в терминале 15ИЭ.

    Правила взяты из `ie15/ie15emu/charset.py`:

    * латиница, цифры и знаки препинания проходят без изменений;
    * управляющие коды (`< 0x20`) — тоже, в том числе `ВК`;
    * русские буквы кладутся в строку `0x60…0x7E` — индекс в `RUS7` плюс
      `0x60`, регистр сворачивает машина;
    * `№` — внутренний код `0x9F` (алфавитный бит плюс `0x1F`);
    * знаки вне семибитного набора заменяются заполнителем `0x7F`;
    * конец строки на линии ДКС — **ETX (0o003)**: ни `dks_line_char`, ни
      `RAW` в SIMH не сворачивают `ПР ПС` в `ПР`, как это делает `vt_fix`
      на линии UTF-8.  Именно поэтому в 15ИЭ конец строки уходит иначе,
      чем при печати на экран.
    """
    out = bytearray()
    for ch in text:
        if ch in INPUT_FALLBACK:
            out.append(INPUT_FALLBACK[ch])
            continue
        if ch == '\u2116':                       # №
            out.append(0x80 | 0x1F)
            continue
        up = ch.upper().replace('\u0401', '\u0415')
        if up in RUS7:
            out.append(0x60 + RUS7.index(up))
            continue
        b = ord(ch)
        if b < 0x20:
            out.append(b)
            continue
        b &= 0x7F
        out.append(b if 0x20 <= b < 0x7F else 0x7F)
    if line_end:
        out.append(ETX)
    return bytes(out)

