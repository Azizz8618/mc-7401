"""
chars.py — знакогенератор терминала «Электроника МС 7401».

Знакомест — 7×8 точек.  Терминал хранит две таблицы знаков (латинскую и
русскую, переключение кодами `S0` / `S1`) и позволяет пользователю
переопределять 64 знака (команда `≡110`, см. `SC_DEFCHAR`).

Модуль решает три задачи:

1. `GLYPHS_LAT` / `GLYPHS_RU` — базовые растровые знаки 7×8 для
   печатаемых кодов 0o40…0o177 (7 бит).
2. `UserCharTable` — таблица 64 переопределяемых знаков, куда СПЕЦ
   (`graf.pas`) загружает «точечные» знаки 3×3 и произвольные 7×7.
3. `render_glyph()` — подготовка знака к выводу в заданном направлении
   (0…7) и размере (0…3).
"""

