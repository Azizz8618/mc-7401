#: Глифы, заменённые типографскими: слотов «Ъ»/«ъ» в ПЗУ нет (32 буквы
#: занимают 0xC0…0xDF и 0xE0…0xFF).  «Ю»/«ю» сюда больше **не** входят:
#: слот 0xE0 цел, прежняя «N» была подменой (см. комментарий выше).
CYR_SUBSTITUTED = frozenset('Ъъ')

#: Латинские и международные знаки в кодах 0x20…0x7F — прямо из ПЗУ,
#: без преобразования: уже знакомест 7×8, одна высота с кириллицей.
GLYPHS_LAT: dict[int, tuple[tuple[int, ...], ...]] = {
    _code: tuple(tuple(1 if c == '#' else 0 for c in _row) for _row in _art)
    for _code, _art in _FONT_7X8_LAT.items()
}

# Русские знаки.  Терминал работает семибитными кодами (ст. 40 статьи:
# «7 бит используется в каждом байте»), поэтому на русской странице
# (`S0`) семибитный код `c` соответствует коду КОИ-8 `c | 0x80`:
# `п` = 0x70, `и` = 0x69, `т` = 0x74.
#
# Таблица строится по стандартному кодеку `koi8-r`, а не вручную:
# прежняя ручная таблица была записана кодами в восьмеричной записи
# вместо шестнадцатеричной (`0o160` = 112 — это не КОИ-8), из-за чего
# все кириллические знаки смещались и выводились случайными рисунками.
GLYPHS_RU: dict[int, tuple[tuple[int, ...], ...]] = {}
for _code7 in range(0x00, 0x80):
    try:
        _ch = bytes((_code7 | 0x80,)).decode('koi8-r')
    except UnicodeDecodeError:                 # pragma: no cover
        continue
    _art = FONT_7X8_CYR.get(_ch)
    if _art is None:
        continue
    GLYPHS_RU[_code7] = tuple(tuple(1 if c == '#' else 0 for c in _row)
                              for _row in _art)

#: Сплошной блок — знак кода 0x7F на странице Н2 (правило 15ИЭ).
FONT_7X8_CYR['█'] = ('#######',) * 8

#: Знаки «пустоты» — коды, которые не должны выводиться.
BLANK_CODES = frozenset({0x00, 0o33, 0o124, 0o125, 0o135, 0o377})


def _to_7x8(pattern: Sequence[int]) -> tuple[tuple[int, ...], ...]:
    """Преобразовать узкий 5×7-знак в знакомест 7×8.

    Больше не используется: латиница берётся из ПЗУ и сразу имеет форму
    7×8 (см. `_FONT_7X8_LAT`).  Оставлена для пользовательских таблиц,
    где знак задают семью **пятиразрядными** байтами-строками
    (`graf.pas`, `ММ:=[376В,…]`): пять полезных столбцов выравниваются
    по левому краю знакоместа, снизу добавляется пустая строка.
    """
    rows: list[tuple[int, ...]] = []
    for pat in pattern:
        row = [0] * GLYPH_W
        for i in range(5):
            if pat & (1 << (4 - i)):
                row[i + 1] = 1
        rows.append(tuple(row))
    rows.append((0,) * GLYPH_W)
    return tuple(rows)


#: Латинские глифы уже в знакоместе 7×8 (данные ПЗУ КР556РТ5) — преобразование
#: `_to_7x8` больше не нужно, иначе буквы снова стали бы ниже кириллицы.
_LAT_MATRIX = dict(GLYPHS_LAT)
#: Русские глифы тоже из ПЗУ — те же семь точек в восьми рядах.
_RU_MATRIX = dict(GLYPHS_RU)


# ─────────────────────────────────────────────────────────────────────────────
# Пользовательская таблица знаков
# ─────────────────────────────────────────────────────────────────────────────

class UserCharTable:
    """64 переопределяемых знака 7×7 (команда `≡110`).

    Знак задаётся семью байтами-строками, по одному на ряд знакоместа;
    точки идут от старшего бита к младшему (бит 7 — левая точка, как в
    `graf.pas`, где строка `[376В,202В,…]` даёт рамку знака).
    """

    def __init__(self) -> None:
        self.chars: list[tuple[int, ...] | None] = [None] * USER_CHARS

    def define(self, index: int, rows: Sequence[int]) -> None:
        if not 0 <= index < USER_CHARS:
            raise IndexError(f'знак {index} вне таблицы 0…{USER_CHARS - 1}')
        if len(rows) != 7:
            raise ValueError('знак должен содержать 7 строк')
        matrix = []
        for r in rows:
            bits = [(r >> (7 - b)) & 1 for b in range(GLYPH_W)]
            matrix.append(tuple(bits))
        self.chars[index] = tuple(matrix)

    def clear(self) -> None:
        self.chars = [None] * USER_CHARS

    def get(self, index: int) -> tuple[tuple[int, ...], ...] | None:
        if not 0 <= index < USER_CHARS:
            return None
        mat = self.chars[index]
        if mat is None:
            return None
        # Знак СПЕЦ задают семью рядами, а знакомест ПЗУ — восемь: восьмой
        # ряд дописывается пустым.  Дописывать надо **семью** точками
        # шириной знакоместа: раньше здесь стояло `(0,)`, и у каждого
        # знака СПЕЦ нижний ряд выходил шириной в одну точку — рамки и
        # заливки рисовались с обрубленным рядом.
        return mat + ((0,) * GLYPH_W,) * (GLYPH_H - len(mat))


#: Глобальная таблица пользовательских знаков терминала.
USER_TABLE = UserCharTable()


# ─────────────────────────────────────────────────────────────────────────────
# Блок описания знака (`≡110≡240 … ≡215`)
# ─────────────────────────────────────────────────────────────────────────────

#: Коды глифов «N точек в знакоместе 3×3» (WN в `graf.pas`): значение → код.
DOT_GLYPH_CODES = {0: 0o60, 1: 0o261, 2: 0o262, 3: 0o63, 4: 0o264,
                   5: 0o65, 6: 0o66, 7: 0o267, 8: 0o270, 9: 0o71}

#: Обратная таблица: код глифа → число точек.  Коды `≡262` и `≡267` в
#: потоках, снятых старыми средствами, приходят перекодированными КОИ-8
#: (0x9D/0x9E) — эти варианты тоже допустимы.
DOT_BY_CODE: dict[int, int] = {v: k for k, v in DOT_GLYPH_CODES.items()}
DOT_BY_CODE.update({0x9D: 2, 0x9E: 7})


def decode_defchar(block: bytes) -> Optional[tuple[int, tuple[int, ...]]]:
    """Разобрать блок описания знака `≡110≡240 … ≡215`.

    Формат (`graf.pas`, процедура `СПЕЦ`): байт кода знака, `≡267≡267`,
    затем семь строк знака — по три глифа `WN`, каждый из которых несёт
    три бита строки (старший глиф — старшие биты).  Возвращает
    `(код знака, 7 строк)` либо None, если блок неполный (в частности,
    если в потоке нет байта кода знака — так бывает в потоках,
    снятых с искажённой транскрипцией `graf.pas`).
    """
    if len(block) < 6:
        return None
    pos = 2                                   # за `≡110≡240`
    code = block[pos]
    pos += 1
    if code in DOT_BY_CODE:                   # код знака не записан
        return None
    rows: list[int] = []
    while pos < len(block) and len(rows) < 7:
        b = block[pos]
        pos += 1
        if b == SC_ENDTEXT:                   # конец знака
            break
        if b not in (SC_ROW, 0o232):          # `≡240` — начало строки
            continue
        if pos + 3 > len(block):
            return None
        vals = [DOT_BY_CODE.get(g) for g in block[pos:pos + 3]]
        pos += 3
        if any(v is None for v in vals):
            return None
        rows.append((vals[0] << 6) | (vals[1] << 3) | vals[2])
    if len(rows) != 7:
        return None
    return code & 0o77, tuple(rows)


# ─────────────────────────────────────────────────────────────────────────────
# Вывод знака
# ─────────────────────────────────────────────────────────────────────────────

#: Направления строки текста: 8 векторов (см. `DIRECTION_VECTORS`).
#: Углы отсчитываются против часовой стрелки от направления «слева направо».
DIRECTION_VECTORS = (
    (1, 0), (0.70711, 0.70711), (0, 1), (-0.70711, 0.70711),
    (-1, 0), (-0.70711, -0.70711), (0, -1), (0.70711, -0.70711),
)


#: Исключения КОИ-8Р: Ё/ё лежат вне буквенных строк (0xA3/0xB3) и по
#: семибитной маске совпали бы с `#` и `3`.
_RU_EXCEPTIONS = {0xA3: 'Ё', 0xB3: 'ё'}

#: Омографы КОИ-8: код русского символа → код латинского омографа.
#: Заглавные: А/А, В/B, Е/E, К/K, М/M, Н/H, О/O, Р/P, С/C, Т/T, Х/X.
#: Строчные: а/a, е/e, о/o, р/p, с/c, х/x.
HOMOGRAPHS: dict[int, int] = {
    0xC1: 0x41,  # А → A
    0xC2: 0x42,  # В → B
    0xC5: 0x45,  # Е → E
    0xCB: 0x4B,  # К → K
    0xCC: 0x4C,  # М → M
    0xCD: 0x48,  # Н → H
    0xCE: 0x4F,  # О → O
    0xD0: 0x50,  # Р → P
    0xD1: 0x43,  # С → C
    0xD4: 0x54,  # Т → T
    0xD8: 0x58,  # Х → X
    0xE1: 0x61,  # а → a
    0xE5: 0x65,  # е → e
    0xEE: 0x6F,  # о → o
    0xF0: 0x70,  # р → p
    0xF1: 0x63,  # с → c
    0xF8: 0x78,  # х → x
}


def _art_matrix(ch: str) -> tuple[tuple[int, ...], ...]:
    """Матрица знака из растра `FONT_7X8_CYR`."""
    art = FONT_7X8_CYR[ch]
    return tuple(tuple(1 if c == '#' else 0 for c in row) for row in art)


def glyph_matrix(code: int, russian: bool) -> tuple[tuple[int, ...], ...]:
    """Матрица знака 7×8 по его коду.

    Сначала проверяется пользовательская таблица (команда `≡110`), затем —
    встроенная таблица текущей страницы шрифта.

    Правила КОИ-8Р:
    * омографы (А/А, В/B, Е/E, К/K, М/M, Н/H, О/O, Р/P, С/C, Т/T, Х/X)
      всегда отображаются латинскими глифами;
    * русские буквы без латинских аналогов (Ё, Й, Ц, У, Ф, Ы, Ь, Ъ, Э, Ю, Я,
      Ш, Щ, Г, Ж, З, П, Л, Д, Ч) — русскими глифами;
    * строчные латинские и русские буквы остаются в своей кодировке.
    """
    ex = _RU_EXCEPTIONS.get(code & 0xFF) if russian else None
    if ex is not None:
        return _art_matrix(ex)
    code &= 0x7F
    if 0 <= code < USER_CHARS:
        custom = USER_TABLE.get(code)
        if custom is not None:
            return custom
    if code < 0x40:
        # Международная строка: одинакова на обеих страницах.
        return _LAT_MATRIX.get(code, _LAT_MATRIX[0o40])
    if code == 0x7F:
        return _art_matrix('█')
    # Омографы всегда отображаются латинскими глифами.
    lat_code = HOMOGRAPHS.get(code, code)
    if lat_code != code:
        return _LAT_MATRIX.get(lat_code, _LAT_MATRIX[0o40])
    # Русские буквы без латинских аналогов — русскими глифами.
    if russian:
        return _RU_MATRIX.get(code, _LAT_MATRIX[0o40])
    return _LAT_MATRIX.get(code, _LAT_MATRIX[0o40])


def dot_pattern(value: int) -> tuple[tuple[int, int, int], ...]:
    """Знак «N точек в знакоместе 3×3» — символы СПЕЦ (`WN` в `graf.pas`).

    `value` = 0…9 — число точек; знакомест заполняется построчно снизу вверх.
    """
    cells = [[0, 0, 0], [0, 0, 0], [0, 0, 0]]
    left = max(0, min(9, value))
    for cy in (2, 1, 0):
        for cx in range(3):
            if left == 0:
                break
            cells[cy][cx] = 1
            left -= 1
        if left == 0:
            break
    return tuple(tuple(r) for r in cells)


def dots_matrix(value: int) -> tuple[tuple[int, ...], ...]:
    """Матрица 7×7 знака из семи трёхразрядных октетов (`WS` в `graf.pas`).

    Семиразрядное значение разбивается на три октета по три бита
    (биты 6…4, 3…1, 0), каждый из которых кодирует знак «N точек в
    знакоместе 3×3» — так СПЕЦ передаёт произвольный рисунок 7×7.
    """
    out = []
    for r in range(7):
        octet = (value >> (6 - 3 * r)) & 0o7
        cells = dot_pattern(octet)
        out.append(tuple(cells[0] + cells[1] + cells[2]))
    return tuple(out)


def scale_matrix(matrix: Sequence[Sequence[int]], size: int) -> list[list[int]]:
    """Увеличить знак в `size` раз (size ≤ 1 — без изменений)."""
    rows = [list(r) for r in matrix]
    if size <= 1:
        return rows
    return [[v for v in row for _ in range(size)] for row in rows for _ in range(size)]


# ── текстовая строка: преобразование знакоместа в экранные смещения ─────────

def _transform(direction: int, size: int):
    """Вернуть отображение (u, v) → (dx, dy) для знака в строке текста.

    `u` — столбец знакоместа (0…6), `v` — строка сверху вниз (0…7),
    `size` — множитель (габарит знака).
    """
    ca, sa = DIRECTION_VECTORS[direction % 8]
    # Поворот знака внутри знакоместа: (u, v) -> ось «вперёд по строке» и
    # «вверх от строки».  Базовый случай d=0: вперёд = u, вверх = -v.
    def xform(u: int, v: int) -> tuple[float, float]:
        # Точка в «локальной» системе: X вперёд, Y вверх от базовой линии.
        # Начало строки — левый край знакоместа, поэтому смещение по X
        # отсчитывается от нуля.  Раньше здесь стояло `u - size * W / 2`,
        # то есть вычиталась половина знакоместа: при нечётной ширине 7
        # получались дробные смещения, округление схлопывало столбцы
        # попарно, и знак выходил зеркальным (см. JOURNAL.md).
        X = u * size
        Y = size * (GLYPH_H - 1 - v)
        return X * ca - Y * sa, X * sa + Y * ca
    return xform


def text_advance(direction: int, size: int) -> tuple[float, float]:
    """Шаг между знаками строки текста (в точках экрана)."""
    ca, sa = DIRECTION_VECTORS[direction % 8]
    step = GLYPH_W * size + 1
    return step * ca, step * sa


def text_offsets(matrix: Sequence[Sequence[int]], direction: int, size: int):
    """Список смещений (dx, dy) для всех зажжённых точек знака.

    Начало строки (базовая линия первого знака) считается точкой (0, 0);
    знак «висит» над ней по направлению 0 и так далее для остальных.
    """
    xform = _transform(direction, size)
    pts = []
    for v, row in enumerate(matrix):
        for u, bit in enumerate(row):
            if not bit:
                continue
            # Масштабирование выполняет `_transform`; если передать ему
            # уже умноженные на `size` координаты, при размере знака
            # больше единицы смещение возведётся в квадрат.
            dx, dy = xform(u, v)
            pts.append((int(round(dx)), int(round(dy))))
    return pts


def render_text(text: bytes, russian: bool, direction: int, size: int,
                start: int = 0) -> list[tuple[int, int]]:
    """Собрать список абсолютных смещений для строки `text`.

    `start` — с какого знака начинать (знаки с S0/S1/управляющими кодами
    в строке не выводятся, но занимают позицию только при явном задании).
    """
    ux, uy = text_advance(direction, size)
    pts: list[tuple[int, int]] = []
    for n, code in enumerate(text):
        mat = glyph_matrix(code, russian)
        for dx, dy in text_offsets(mat, direction, size):
            pts.append((int(round(ux * n + dx)), int(round(uy * n + dy))))
    return pts

