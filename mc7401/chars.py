# ── Кириллица ─────────────────────────────────────────────────────────────
#
# ПРОИСХОЖДЕНИЕ ДАННЫХ. Точных начертаний знаков МС7401 нет: статья
# «Дисплейные микроконтроллеры семейства МИДИКОН» (МПСС, 1989, № 5,
# стр. 38-43) шрифта не содержит — модуль вывода МС7401 выполняет
# примитив «строка текста», а знаки формирует сторона ЭВМ; `graf1.pas`
# содержит только таблицу соответствия кодов, без растровых данных.
#
# Поэтому начертания взяты из другого измеренного источника — дампа
# знакогенератора КР556РТ5 терминала «Электроника-15ИЭ»
# (`ie15/rom/chargen-15ie.bin`, 2048 байт = 256 глифов × 8 строк × 7 точек).
# Организация совпадает с нашим знакоместом 7×8, и это реальные
# измеренные растры, а не типографская реконструкция.
#
# Адресация ПЗУ (см. `ie15/docs/ROM-ANALYSIS.md`): слот 0xE0 + i —
# i-я заглавная буква порядка `ЮАБЦДЕФГХИЙКЛМНОПЯРСТУЖВЬЫЗШЭЩЧ`,
# слот 0xC0 + i — соответствующая строчная, слот 0xDF — «ъ».
#
# ЧТО ОСТАЁТСЯ НЕПРОВЕРЕННЫМ: это шрифт 15ИЭ, а не МС7401. Форма 7×8
# совпадает, начертания могут отличаться. Слоты «Ъ»/«ъ» в ПЗУ нет вовсе
# (32 буквы занимают 0xC0…0xDF и 0xE0…0xFF), их начертания типографские —
# см. `CYR_SUBSTITUTED`.
