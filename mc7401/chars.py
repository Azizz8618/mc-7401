def _to_7x8(pattern: Sequence[int]) -> tuple[tuple[int, ...], ...]:
    """Преобразовать узкий 5×7-знак в знакомест 7×8.

    Пять «полезных» столбцов знака выравниваются по левому краю знакоместа
    (по одному пустому столбцу слева и справа), снизу добавляется пустая
    строка — так знаки выравниваются по верхнему краю знакоместа.
    """
    rows: list[tuple[int, ...]] = []
    for pat in pattern:
        row = [0] * GLYPH_W
        for i in range(5):
            if pat & (1 << (4 - i)):
                row[i + 1] = 1
        rows.append(tuple(row))
    rows.append((0,) * GLYPH_W)
    return tuple(rows)


_LAT_MATRIX = {c: _to_7x8(p) for c, p in GLYPHS_LAT.items()}
_RU_MATRIX = {c: _to_7x8(p) for c, p in GLYPHS_RU.items()}


