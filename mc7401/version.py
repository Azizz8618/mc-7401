"""
version.py — единственный источник номера версии эмулятора.

Номер живёт в отдельном модуле, а не прямо в `__init__.py`, чтобы его
можно было взять отовсюду, не поднимая пакет целиком: из заголовка
окна, из заставки, из `--version` и из `pyproject.toml`.

Приложение обязано показывать версию на виду — иначе не отличить новую
сборку от старой, а терминал запускают именно затем, чтобы посмотреть,
что изменилось.

    >>> import mc7401.version
    >>> mc7401.version.version()
    '1.1.0'
"""

from __future__ import annotations

#: Номер версии эмулятора, `MAJOR.MINOR.PATCH`:
#:
#: * `MAJOR` — несовместимое изменение интерфейса или протокола;
#: * `MINOR` — новые возможности (в этом наборе правок: отмена
#:   в режиме «С ЭВМ», виды пера и толщина, ровная склейка истории
#:   с кадром, работающие `PgUp`/`PgDn`);
#: * `PATCH` — исправления без новых возможностей.
VERSION = '1.1.0'


def version() -> str:
    """Номер версии строкой — для `--version` и проверок."""
    return VERSION


def short() -> str:
    """Короткая метка версии для экрана: знаки ПЗУ не знают `+`."""
    return 'вер. ' + VERSION.replace('.', '-')


def window_title() -> str:
    """Заголовок окна: модель терминала и версия эмулятора.

    Версия в заголовке видна всегда — в списке окон, в панели задач и на
    снимке экрана.  Без неё «запустил и не понял, та ли это сборка».
    """
    from .startup import MODEL
    return f'{MODEL} — эмулятор {VERSION}'


__all__ = ['VERSION', 'version', 'short', 'window_title']