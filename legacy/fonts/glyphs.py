def get_glyph(code: int, font: str = "EN") -> Optional[list[int]]:
    """
    Получить базовый 8×8 глиф по коду символа.

    Параметры:
        code — код символа (0..255);
        font — 'EN' (ASCII) или 'RU' (KOI-8Р).

    Возвращает список из 8 целых (строки битмапа) или None, если глиф
    не найден.
    """
    if font == "RU":
        # Пробуем найти по коду КОИ-8Р, декодировав в Unicode.
        try:
            ch = bytes([code]).decode(KOI8_R)
        except UnicodeDecodeError:
            return None
        if ord(ch) in FONT_8X8:
            return FONT_8X8[ord(ch)]
        return None

    if code in FONT_8X8:
        return FONT_8X8[code]
    return None


def get_fallback_glyph() -> list[int]:
    """Заглушка для символов, которых нет в таблице."""
    return list(_PLACEHOLDER)


def render_glyph(
    code: int,
    *,
    font: str = "EN",
    size: int = 1,
    placeholder: bool = True,
) -> Bitmap:
    """
    Отрисовать один символ как битмап.

    Параметры:
        code        — код символа (0..255);
        font        — 'EN' или 'RU';
        size        — масштаб (1..4);
        placeholder — если True, для отсутствующих глифов возвращается
                      заглушка-прямоугольник; иначе — пустой битмап.

    Возвращает список строк (каждая — список 0/1).
    """
    size = max(1, min(MAX_SCALE, int(size)))

    rows = get_glyph(code, font)
    if rows is None:
        if not placeholder:
            return [[0] * (GLYPH_W * size) for _ in range(GLYPH_H * size)]
        rows = get_fallback_glyph()

    # Разворачиваем в 2D 8×8.
    base: Bitmap = []
    for r in rows:
        base.append([(r >> (7 - i)) & 1 for i in range(GLYPH_W)])

    if size == 1:
        return base

    # Масштабирование: дублируем пиксели.
    scaled: Bitmap = []
    for row in base:
        wide = []
        for px in row:
            wide.extend([px] * size)
        for _ in range(size):
            scaled.append(wide[:])
    return scaled


def render_text(
    text: str,
    *,
    font: str = "RU",
    size: int = 1,
) -> list[Bitmap]:
    """
    Отрисовать строку текста как список битмапов (по одному на символ).

    Параметры:
        text — строка Unicode;
        font — 'RU' или 'EN' (используется для кодировки в байты);
        size — масштаб (1..4).
    """
    encoding = KOI8_R if font == "RU" else "latin-1"
    result: list[Bitmap] = []
    for ch in text:
        try:
            code = ch.encode(encoding)[0]
        except (UnicodeEncodeError, IndexError):
            code = 0x3F  # '?'
        result.append(render_glyph(code, font=font, size=size))
    return result


# ─────────────────────────────────────────────────────────────────────────────
# Работа с восьмеричным представлением битмапа
# ─────────────────────────────────────────────────────────────────────────────
#
# В graf.pas битмапы задаются как массивы восьмеричных значений:
#     ММ:=[376В,202В,202В,202В,202В,202В,376В]
# Это 7 байт, описывающих 7 строк знакоместа. Восьмая строка — пустая.

def bitmap_to_octal(rows: list[int]) -> list[str]:
    """
    Преобразовать список целых (0..255) в список восьмеричных строк.

    Пример:
        >>> bitmap_to_octal([0xFE, 0x82, 0x82])
        ['376', '202', '202']
    """
    return [format(r, "o") for r in rows]


def octal_to_bitmap(octals: Iterable[str]) -> list[int]:
    """
    Преобразовать восьмеричные строки в список целых.

    Пример:
        >>> octal_to_bitmap(['376', '202', '202'])
        [254, 130, 130]
    """
    return [int(s, 8) for s in octals]


def parse_graf_bitmap(s: str) -> list[int]:
    """
    Разобрать строку вида "376В,202В,202В,..." в список целых.

    Поддерживает «В» (или «B») как суффикс восьмеричного числа,
    который используется в graf.pas.
    """
    parts = s.replace("В", "").replace("B", "").replace("b", "").split(",")
    return [int(p.strip(), 8) for p in parts if p.strip()]


def render_bitmap_ascii(rows: list[int], *, on: str = "#", off: str = ".") -> str:
    """
    Нарисовать битмап ASCII-символами (для отладки).

    Пример:
        >>> print(render_bitmap_ascii([0b11111111, 0b10000001]))
        ########
        #......#
    """
    lines: list[str] = []
    for r in rows:
        bits = [(r >> (7 - i)) & 1 for i in range(8)]
        lines.append("".join(on if b else off for b in bits))
    return "\n".join(lines)


