FONT_8X8: dict[int, list[int]] = {}


def _add(ch: str, rows: list[int], *, font: str = "EN") -> None:
    """Добавить глиф в таблицу по коду символа."""
    if len(rows) != GLYPH_H:
        raise ValueError(f"Глиф {ch!r}: ожидалось {GLYPH_H} строк, дано {len(rows)}")
    for r in rows:
        if not 0 <= r <= 0xFF:
            raise ValueError(f"Глиф {ch!r}: строка {r:#x} вне 0..255")
    code = ord(ch)
    FONT_8X8[code] = rows


